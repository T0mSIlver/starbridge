/** Draws the SVG onto a canvas of width × height, which keeps what it leaves out transparent. */
async function png({ viewBox, body }: Svg, width: number, height = width): Promise<Buffer> {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${width}" height="${height}">${body}</svg>`;
  const src = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
  const url = await page.evaluate(
    async ([src, width, height]) => {
      const img = new Image(width, height);
      img.src = src;
      await img.decode();
      const c = document.createElement("canvas");
      c.width = width;
      c.height = height;
      c.getContext("2d")?.drawImage(img, 0, 0, width, height);
      return c.toDataURL("image/png");
    },
    [src, width, height] as const,
  );
  return Buffer.from(url.split(",")[1] ?? "", "base64");
}

/** Renders an opaque page of width × height. */
async function html(content: string, width: number, height: number): Promise<Buffer> {
  await page.setViewportSize({ width, height });
  await page.setContent(`<!doctype html><style>*{margin:0}</style>${content}`);
  await page.evaluate(() => document.fonts.ready);
  return await page.screenshot({ clip: { x: 0, y: 0, width, height } });
}

/** An ICO whose entries are PNGs, which every browser that reads favicon.ico accepts. */
function ico(images: { size: number; data: Buffer }[]): Buffer {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size % 256, e);
    head.writeUInt8(size % 256, e + 1);
    head.writeUInt16LE(1, e + 4);
    head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(data.length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([head, ...images.map((x) => x.data)]);
}

