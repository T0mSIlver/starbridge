type Pt = [number, number];
type Seg =
  | { op: "M"; to: Pt }
  | { op: "L"; to: Pt }
  | { op: "C"; c1: Pt; c2: Pt; to: Pt }
  | { op: "Z" };

/** The arch as moves, lines and cubic curves, for drawing APIs without SVG arcs (SwiftUI). */
function segments(d: string): Seg[] {
  const tokens = d.match(/[MLHVAZ]|-?\d*\.?\d+(?:e-?\d+)?/gi) ?? [];
  const out: Seg[] = [];
  let i = 0;
  let cur: Pt = [0, 0];
  const num = () => Number(tokens[i++]);
  while (i < tokens.length) {
    const op = tokens[i++];
    if (op === "M" || op === "L") {
      cur = [num(), num()];
      out.push({ op, to: cur });
    } else if (op === "H") {
      cur = [num(), cur[1]];
      out.push({ op: "L", to: cur });
    } else if (op === "V") {
      cur = [cur[0], num()];
      out.push({ op: "L", to: cur });
    } else if (op === "Z") out.push({ op: "Z" });
    else if (op === "A") {
      const [rx, , , large, sweep, x, y] = [num(), num(), num(), num(), num(), num(), num()];
      out.push(...arc(cur, [x, y], rx, large === 1, sweep === 1));
      cur = [x, y];
    } else throw new Error(`design/mark.svg: the arch uses ${op}; use absolute M, L, H, V, A, Z`);
  }
  return out;
}

/** A circular SVG arc as cubic curves, at most a quarter turn each (SVG 1.1, appendix F.6.5). */
function arc(from: Pt, to: Pt, r: number, large: boolean, sweep: boolean): Seg[] {
  const [x1, y1] = from,
    [x2, y2] = to;
  const mx = (x1 - x2) / 2,
    my = (y1 - y2) / 2;
  const half = Math.hypot(mx, my);
  r = Math.max(r, half);
  const k0 = (Math.sqrt(Math.max(0, r * r - half * half)) / half) * (large === sweep ? -1 : 1);
  const cx = (x1 + x2) / 2 + k0 * my,
    cy = (y1 + y2) / 2 - k0 * mx;
  let a1 = Math.atan2(y1 - cy, x1 - cx);
  let da = Math.atan2(y2 - cy, x2 - cx) - a1;
  if (sweep && da < 0) da += 2 * Math.PI;
  if (!sweep && da > 0) da -= 2 * Math.PI;
  const n = Math.ceil(Math.abs(da) / (Math.PI / 2) - 1e-9);
  const step = da / n,
    k = (4 / 3) * Math.tan(step / 4);
  const segs: Seg[] = [];
  for (let s = 0; s < n; s++) {
    const a2 = a1 + step;
    const p1: Pt = [cx + r * Math.cos(a1), cy + r * Math.sin(a1)];
    const p2: Pt = [cx + r * Math.cos(a2), cy + r * Math.sin(a2)];
    segs.push({
      op: "C",
      c1: [p1[0] - k * r * Math.sin(a1), p1[1] + k * r * Math.cos(a1)],
      c2: [p2[0] + k * r * Math.sin(a2), p2[1] - k * r * Math.cos(a2)],
      to: s === n - 1 ? to : p2,
    });
    a1 = a2;
  }
  return segs;
}

const SEGS = segments(ARCH);
const points = SEGS.flatMap((s) =>
  s.op === "Z" ? [] : s.op === "C" ? [s.c1, s.c2, s.to] : [s.to],
);
const BOX = {
  x0: Math.min(...points.map((p) => p[0])),
  x1: Math.max(...points.map((p) => p[0])),
  y0: Math.min(...points.map((p) => p[1])),
  y1: Math.max(...points.map((p) => p[1])),
};
// The mark alone (rails, lockups, the tab and menu bar icons): a square as wide as the arch, its
// bottom edge on the arch's feet, where a lockup's name stands.
const W = BOX.x1 - BOX.x0;
const CROP = { x: BOX.x0, y: BOX.y1 - W, size: W };
// The same, with room for a halo or for pixels to round.
const PAD = W * 0.06;
const SMALL = { x: CROP.x - PAD, y: CROP.y - PAD, size: W + 2 * PAD };
// The menu bar and the tab: as wide, with the arch centred top to bottom, as macOS centres the image
// in the bar and the system icons in their own, and a browser centres a favicon in its 16 px box.
// On its feet, the menu bar icon sat 1.5 px below the system icons at 1x (#1449), and the tab icon
// as low (#1562).
const CENTRED = { ...SMALL, y: (BOX.y0 + BOX.y1) / 2 - SMALL.size / 2 };
const TRAY = CENTRED;
const vb = (c: { x: number; y: number; size: number }) =>
  `${r(c.x)} ${r(c.y)} ${r(c.size)} ${r(c.size)}`;

function r(n: number): number {
  return Math.round(n * 1000) / 1000;
}

