function attr(id: string, name: string): string {
  const el = source.match(new RegExp(`<[^>]*id="${id}"[^>]*>`))?.[0];
  const value = el?.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
  if (value === undefined) throw new Error(`design/mark.svg: #${id} has no ${name}`);
  return value;
}
